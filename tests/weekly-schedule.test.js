/* Weekly workout schedule, manual selection, safe backup and data-health tests. */
'use strict';
const assert=require('node:assert/strict');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const schedule=require(path.join(root,'weekly-workout-schedule.js'));
const exporter=require(path.join(root,'recovery-export.js'));
const importer=require(path.join(root,'recovery-import.js'));
const health=require(path.join(root,'data-health.js'));
const map=new Map();
const storage={getItem:key=>map.has(key)?map.get(key):null,setItem:(key,val)=>map.set(key,String(val)),removeItem:key=>map.delete(key)};
const custom=[{id:'custom-10',title:'My Monday',ids:['chest-press']}];
const presets=[{id:'upper-a',title:'Upper A',ids:['chest-press']},{id:'lower-a',title:'Lower A',ids:['leg-press']}];
const monday=new Date(2026,10,16,12);
const tuesday=new Date(2026,10,17,12);
assert.equal(schedule.resolve({storage,custom,presets,date:monday}).id,'custom-10');
schedule.assign(storage,1,'lower-a',[...custom,...presets]);
assert.equal(schedule.resolve({storage,custom,presets,date:monday}).id,'lower-a');
assert.equal(schedule.resolve({storage,custom,presets,date:tuesday}).id,'custom-10');
storage.setItem('mlc2-selected-workout-v1','custom-10');
const manual=schedule.resolve({storage,custom,presets,date:monday});
assert.equal(manual.id,'custom-10');
assert.equal(manual.scheduleSource,'manual');
schedule.clearOverride(storage);
assert.equal(schedule.resolve({storage,custom,presets,date:monday}).id,'lower-a');
assert.throws(()=>schedule.assign(storage,1,'nonexistent',[...custom,...presets]),/Unknown workout/);
assert.throws(()=>schedule.assign(storage,7,'upper-a',[...custom,...presets]),/Unknown weekday/);
schedule.assign(storage,1,'',[...custom,...presets]);
assert.equal(schedule.resolve({storage,custom,presets,date:monday}).id,'custom-10');
schedule.assign(storage,1,'custom-10',[...custom,...presets]);
const snapshot=exporter.createBackup(storage);
assert.equal(snapshot.data['mlc2-weekly-schedule-v1']['1'],'custom-10');
const parsed=importer.parse(JSON.stringify(snapshot));
const restored=new Map();
const output={getItem:k=>restored.has(k)?restored.get(k):null,setItem:(k,v)=>restored.set(k,String(v)),removeItem:k=>restored.delete(k)};
importer.restore(parsed,output);
assert.equal(schedule.read(output)['1'],'custom-10');
const bad=JSON.parse(JSON.stringify(snapshot));
bad.data['mlc2-weekly-schedule-v1']={'8':'upper-a'};
assert.throws(()=>importer.parse(JSON.stringify(bad)),/Invalid weekly workout schedule/);
const badId=JSON.parse(JSON.stringify(snapshot));
badId.data['mlc2-weekly-schedule-v1']={'1':'INVALID!ID'};
assert.throws(()=>importer.parse(JSON.stringify(badId)),/Invalid weekly workout schedule/);
const ok=health.check(storage,[{id:'chest-press'}],presets.concat(custom));
assert.equal(ok.counts['Scheduled weekdays'],1);
storage.setItem('mlc2-weekly-schedule-v1',JSON.stringify({'1':'missing-workout'}));
const missing=health.check(storage,[{id:'chest-press'}],presets.concat(custom));
assert.ok(missing.warnings.some(x=>x.includes('missing workout')));
assert.equal(schedule.resolve({storage,custom,presets,date:monday}).id,'custom-10');
console.log('MYLIFTCOACH weekly schedule: PASS — day routing, manual override, backup, validation');
